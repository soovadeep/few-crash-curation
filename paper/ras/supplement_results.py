"""Generate revision table, numerical macros and figure from stored dive outcomes.

Run: python paper/ras/supplement_results.py [--check]
Requires numpy, scipy and matplotlib. --check checks the numerical TeX artifacts.
"""
import argparse
import json
from pathlib import Path

import numpy as np
from scipy.stats import t

HERE = Path(__file__).resolve().parent
RESULTS = HERE.parents[1] / "results" / "drone"
SCALES = (0.5, 1, 2)
METHODS = ("fact", "l2rw_la")


def stats(values):
    values = np.asarray(values)
    mean = values.mean()
    se = values.std(ddof=1) / np.sqrt(len(values))
    half = t.ppf(0.975, len(values) - 1) * se
    return mean, se, mean - half, mean + half


def rates(runs):
    assert len(runs) == 72
    assert all(r["safe"] == (r["reach"] and not r["crash"]) for r in runs)
    return np.array([100 * np.mean([r[k] for r in runs]) for k in ("crash", "safe")])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = {}
    for scale in SCALES:
        for method in METHODS:
            group = []
            for seed in range(1, 6):
                path = RESULTS / "ras_cost" / f"seed-{seed}" / f"{method}-cost{scale}.json"
                result = json.loads(path.read_text())
                assert (result["seed"], result["method"], result["scale"], result["pilot"]) == (seed, method, scale, False)
                group.append(rates(result["runs"]))
            data[scale, method] = np.array(group)

    macros = {}
    for scale, prefix in ((0.5, "Low"), (1, "Default"), (2, "High")):
        for index, metric in enumerate(("Crash", "Safe")):
            mean, _, lo, hi = stats(data[scale, "l2rw_la"][:, index] - data[scale, "fact"][:, index])
            macros[prefix + metric + "Gap"] = f"{mean:.2f}"
            macros[prefix + metric + "CI"] = f"[{lo:.2f},{hi:.2f}]"
    ablation = {}
    for method in ("fact", "gradfree"):
        ablation[method] = np.array([
            rates([r for group in json.loads((RESULTS / f"reach_{method}_prop50j8m_s{seed}.json").read_text())["runs"].values() for r in group])
            for seed in range(1, 4)])
    mean, _, lo, hi = stats(ablation["fact"][:, 1] - ablation["gradfree"][:, 1])
    macros["LookSafeGain"] = f"{mean:.1f}"
    macros["LookSafeCI"] = f"[{lo:.1f},{hi:.1f}]"
    numbers = "% Generated by supplement_results.py; percentages or percentage points.\n"
    numbers += "".join("\\newcommand{\\" + key + "}{" + value + "}\n" for key, value in macros.items())
    table = r"""% Generated by supplement_results.py from results/drone/ras_cost.
\begin{table}[t]
\centering
\caption{Controller-cost sensitivity on the thrust-gain fault. Rates are percentages, mean $\pm$ SE over five training seeds (72 paired dives per seed and setting). Each trained model is frozen across all three multipliers. Safe completion requires reaching the goal without a collision anywhere in the trajectory.}
\label{tab:cost_sensitivity}
\begin{tabular}{rlrr}
\toprule
Multiplier & Method & Crash (\%) & Safe completion (\%) \\
\midrule
"""
    for scale in SCALES:
        for method, label in (("fact", r"\method{}"), ("l2rw_la", "Reweighting (look-ahead)")):
            cells = [stats(data[scale, method][:, index]) for index in (0, 1)]
            table += f"{scale:g} & {label} & " + " & ".join(f"${m:.2f} \\pm {se:.2f}$" for m, se, _, _ in cells) + r" \\" + "\n"
    table += "\\bottomrule\n\\end{tabular}\n\\end{table}\n"
    for name, content in (("supplement_numbers.tex", numbers), ("cost_table.tex", table)):
        if args.check:
            assert (HERE / name).read_text() == content, f"stale {name}: regenerate"
        else:
            (HERE / name).write_text(content)
    if args.check:
        print("Supplement: all 2,160 dive outcomes and paired ablation numbers match TeX.")
        return

    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    plt.rcParams.update({"font.family": "serif", "font.size": 10, "pdf.fonttype": 42})
    fig, ax = plt.subplots(figsize=(5.3, 3.6), layout="constrained")
    for method, label, marker, color in (("fact", "FACT", "o", "#12638d"), ("l2rw_la", "Reweighting (look-ahead)", "s", "#a84920")):
        centers = np.array([[stats(data[s, method][:, i])[0] for i in (0, 1)] for s in SCALES])
        errors = np.array([[stats(data[s, method][:, i])[1] for i in (0, 1)] for s in SCALES])
        ax.errorbar(centers[:, 0], centers[:, 1], xerr=errors[:, 0], yerr=errors[:, 1], fmt=marker + "-", color=color, label=label, capsize=3, linewidth=1.2)
        for scale, (x, y) in zip(SCALES, centers):
            ax.annotate(f"{scale:g}×", (x, y), xytext=(5, -14), textcoords="offset points", fontsize=9)
    ax.set(xlabel="Crash rate (%)", ylabel="Safe completion (%)", xlim=(0, 13), ylim=(40, 94))
    ax.legend(loc="lower right", frameon=False)
    ax.grid(alpha=0.2)
    ax.spines[["top", "right"]].set_visible(False)
    fig.savefig(HERE.parent / "figs" / "fig_cost_sensitivity.pdf")
    plt.close(fig)
    print("Generated cost table, paired-interval macros and Figure 4.")


if __name__ == "__main__":
    main()
