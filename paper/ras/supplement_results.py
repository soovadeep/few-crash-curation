"""Write Table 4, the Section 7.3.1 numbers and Fig. 4 from the stored controller-cost dives.

Run: python paper/ras/supplement_results.py [--check]
Requires numpy, scipy and matplotlib. --check checks the numerical TeX artifacts.
"""
import argparse
import json
from pathlib import Path

import numpy as np
from scipy.stats import t

HERE = Path(__file__).resolve().parent
RESULTS = HERE.parents[1] / "results" / "drone"
METHODS = ("fact", "l2rw_la")
# Multipliers flown by each method (as in code/drone/work/ras_supplement.py).
METHOD_SCALES = {"fact": (0.5, 1, 2), "l2rw_la": (0.5, 1, 2, 4, 8, 16)}


def stats(values):
    values = np.asarray(values)
    mean = values.mean()
    se = values.std(ddof=1) / np.sqrt(len(values))
    half = t.ppf(0.975, len(values) - 1) * se
    return mean, se, mean - half, mean + half


def rates(runs):
    assert len(runs) == 72
    assert all(r["safe"] == (r["reach"] and not r["crash"]) for r in runs)
    return np.array([100 * np.mean([r[k] for r in runs]) for k in ("crash", "safe")])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = {}
    for method in METHODS:
        for scale in METHOD_SCALES[method]:
            group = []
            for seed in range(1, 6):
                path = RESULTS / "ras_cost" / f"seed-{seed}" / f"{method}-cost{scale}.json"
                result = json.loads(path.read_text())
                assert (result["seed"], result["method"], result["scale"], result["pilot"]) == (seed, method, scale, False)
                group.append(rates(result["runs"]))
            data[scale, method] = np.array(group)

    macros = {}
    for scale, prefix in ((0.5, "Low"), (1, "Default"), (2, "High")):
        for index, metric in enumerate(("Crash", "Safe")):
            mean, _, lo, hi = stats(data[scale, "l2rw_la"][:, index] - data[scale, "fact"][:, index])
            macros[prefix + metric + "Gap"] = f"{mean:.1f}"
            macros[prefix + metric + "CI"] = f"[{lo:.1f},{hi:.1f}]"
    # Matched operating points: about equal crash rates, about equal safe completion, and a stronger penalty.
    for name, (a, b) in (("EqRisk", ((2, "l2rw_la"), (0.5, "fact"))), ("EqSafe", ((8, "l2rw_la"), (2, "fact"))),
                         ("RWFour", ((4, "l2rw_la"), (2, "l2rw_la")))):
        for index, metric in enumerate(("Crash", "Safe")):
            mean, _, lo, hi = stats(data[a][:, index] - data[b][:, index])
            macros[name + metric + "Gap"] = f"{mean:.1f}"
            macros[name + metric + "CI"] = f"[{lo:.1f},{hi:.1f}]"
    rw_crash = [data[scale, "l2rw_la"][:, 0].mean() for scale in METHOD_SCALES["l2rw_la"]]
    macros["RWCrashMin"] = f"{min(rw_crash):.1f}"
    macros["RWCrashMax"] = f"{max(rw_crash):.1f}"
    macros["RWSafeTwo"] = f"{data[2, 'l2rw_la'][:, 1].mean():.1f}"
    macros["RWSafeSixteen"] = f"{data[16, 'l2rw_la'][:, 1].mean():.1f}"
    macros["FactCrashOne"] = f"{data[1, 'fact'][:, 0].mean():.1f}"
    macros["FactCrashTwo"] = f"{data[2, 'fact'][:, 0].mean():.1f}"
    macros["CostDives"] = f"{72 * 5 * len(data):,}"
    # At the default multiplier the controller-cost dives are the dives of Table 2 (reach_*), outcome for outcome.
    for method in METHODS:
        for seed in range(1, 6):
            old = json.loads((RESULTS / f"reach_{method}_gain40j8_s{seed}.json").read_text())["runs"]
            new = json.loads((RESULTS / "ras_cost" / f"seed-{seed}" / f"{method}-cost1.json").read_text())["runs"]
            old_rows = [(task, r) for task, group in old.items() for r in group]
            assert [task for task, _ in old_rows] == [r["task"] for r in new]
            assert all((a["crash"], a["safe"], a["final_dist"]) == (b["crash"], b["safe"], b["final_dist"])
                       for (_, a), b in zip(old_rows, new)), f"{method} seed {seed}: default dives differ from Table 2"
    # Every seed's FACT removes exactly the faulty flights.
    for seed in range(1, 6):
        prep = json.loads((RESULTS / "ras_cost" / f"seed-{seed}" / "preparation.json").read_text())
        assert (prep["bad_removed"], prep["correct_removed"]) == (32, 0)
    ablation = {}
    for method in ("fact", "gradfree"):
        ablation[method] = np.array([
            rates([r for group in json.loads((RESULTS / f"reach_{method}_prop50j8m_s{seed}.json").read_text())["runs"].values() for r in group])
            for seed in range(1, 4)])
    mean, _, lo, hi = stats(ablation["fact"][:, 1] - ablation["gradfree"][:, 1])
    macros["LookSafeGain"] = f"{mean:.1f}"
    macros["LookSafeCI"] = f"[{lo:.1f},{hi:.1f}]"
    numbers = "% Generated by supplement_results.py; percentages or percentage points.\n"
    numbers += "".join("\\newcommand{\\" + key + "}{" + value + "}\n" for key, value in macros.items())
    table = r"""% Generated by supplement_results.py from results/drone/ras_cost.
\begin{table}[t]
\centering
\caption{Controller-cost sensitivity on the thrust-gain fault. Rates are percentages, mean $\pm$ SE over five training seeds (72 paired dives per seed and setting). Each trained model is frozen across all multipliers; reweighting is also flown at 4, 8 and 16. At multiplier 1 the dives are those of Table~\ref{tab:safe}. Safe completion requires reaching the goal without a collision anywhere in the trajectory.}
\label{tab:cost_sensitivity}
\begin{tabular}{rlrr}
\toprule
Multiplier & Method & Crash (\%) & Safe completion (\%) \\
\midrule
"""
    labels = {"fact": r"\method{}", "l2rw_la": "Reweighting (look-ahead)"}
    for scale, method in sorted(data, key=lambda key: (key[0], METHODS.index(key[1]))):
        cells = [stats(data[scale, method][:, index]) for index in (0, 1)]
        table += f"{scale:g} & {labels[method]} & " + " & ".join(f"${m:.1f} \\pm {se:.1f}$" for m, se, _, _ in cells) + r" \\" + "\n"
    table += "\\bottomrule\n\\end{tabular}\n\\end{table}\n"
    for name, content in (("supplement_numbers.tex", numbers), ("cost_table.tex", table)):
        if args.check:
            assert (HERE / name).read_text() == content, f"stale {name}: regenerate"
        else:
            (HERE / name).write_text(content)
    if args.check:
        print(f"Supplement: all {macros['CostDives']} dive outcomes and paired ablation numbers match TeX.")
        return

    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    # Same style as make_figs.py: STIX type, thin axes, FACT in the curation blue, the baseline in grey.
    plt.rcParams.update({"font.size": 8.5, "font.family": "STIXGeneral", "mathtext.fontset": "stix",
                         "axes.linewidth": 0.5, "axes.spines.top": False, "axes.spines.right": False,
                         "xtick.major.width": 0.5, "ytick.major.width": 0.5, "xtick.major.size": 2,
                         "ytick.major.size": 2, "legend.frameon": False, "pdf.fonttype": 42})
    ink, muted, grid = "#0b0b0b", "#6f6e69", "#e6e5e0"
    styles = (("fact", "FACT", "o", "#2a78d6"), ("l2rw_la", "Learning to reweight (look-ahead)", "s", "#7d7c77"))
    # Multiplier labels, offset in points from each mean so they clear the error bars.
    offsets = {0.5: (7, 6, "left", "bottom"), 1: (-7, 6, "right", "bottom"), 2: (7, -6, "left", "top"),
               4: (7, 4, "left", "bottom"), 8: (7, 4, "left", "bottom"), 16: (7, 4, "left", "bottom")}
    fig, ax = plt.subplots(figsize=(5.6, 3.3), layout="constrained")
    for method, label, marker, color in styles:
        scales = METHOD_SCALES[method]
        centers = np.array([[stats(data[s, method][:, i])[0] for i in (0, 1)] for s in scales])
        errors = np.array([[stats(data[s, method][:, i])[1] for i in (0, 1)] for s in scales])
        ax.plot(centers[:, 0], centers[:, 1], "-", color=color, lw=1.2, alpha=0.55, zorder=2,
                solid_capstyle="round")
        ax.errorbar(centers[:, 0], centers[:, 1], xerr=errors[:, 0], yerr=errors[:, 1], fmt="none",
                    ecolor=color, elinewidth=1.0, capsize=3, capthick=1.0, zorder=3)
        ax.plot(centers[:, 0], centers[:, 1], marker, ms=5.5, color=color, mec="white", mew=0.8,
                zorder=4, label=label)
        for scale, (x, y) in zip(scales, centers):
            dx, dy, ha, va = offsets[scale]
            ax.annotate(f"{scale:g}×", (x, y), xytext=(dx, dy), textcoords="offset points",
                        ha=ha, va=va, fontsize=7.5, color=muted)
    ax.annotate("", xy=(0.6, 92), xytext=(2.4, 80),
                arrowprops=dict(arrowstyle="-|>", color=muted, lw=0.6, mutation_scale=7))
    ax.text(2.5, 79, "better", fontsize=7.5, color=muted, ha="left", va="top", style="italic")
    ax.set(xlabel="Dives that crash (%)", ylabel="Safe completion (%)", xlim=(0, 14), ylim=(10, 95))
    ax.set_xticks(range(0, 15, 2))
    ax.grid(color=grid, lw=0.5)
    ax.set_axisbelow(True)
    ax.legend(loc="lower left", handlelength=1.0, handletextpad=0.5, borderaxespad=0.2)
    fig.savefig(HERE.parent / "figs" / "fig_cost_sensitivity.pdf")
    plt.close(fig)
    print("Generated cost table, paired-interval macros and Figure 4.")


if __name__ == "__main__":
    main()
